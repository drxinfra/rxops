class ServersGoldenTest(unittest.TestCase):
    def test_golden(self):
        for name, hash_, expected in SERVERS:
            with self.subTest(name):
                res = S.compute(S.servers_inputs(url="#" + hash_))
                got = digest(res)
                for key in ("d", "grand", "warn"):
                    self.assertEqual(got[key], expected[key], "%s: %s" % (name, key))
                self.assertEqual(len(got["contours"]), len(expected["contours"]), name)
                for gc, ec in zip(got["contours"], expected["contours"]):
                    self.assertEqual(gc[:5], ec[:5], "%s: контур %s" % (name, ec[0]))
                    self.assertEqual(gc[5], ec[5], "%s: узлы контура %s" % (name, ec[0]))
                self.assertEqual(got["strings"], expected["strings"], "%s: строки ролей, ПО и замечаний" % name)

    def test_blog_example(self):
        """Пример из статьи https://drxinfra.ru/blog/rx-sizing-servers-disks.html: 300 человек, 60 000 документов."""
        res = S.compute(S.servers_inputs())
        prod = res["contours"][0]
        self.assertEqual((res["d"]["U"], res["d"]["storeGB"], res["d"]["dbGB"]), (90, 180, 70))
        self.assertEqual(prod["totals"], {"vms": 5, "cpu": 22, "ram": 52, "disk": 780})
        self.assertEqual(prod["backupGB"], 450)
        self.assertEqual(prod["logs"]["perDay"], 1.1)
        self.assertEqual((res["grand"]["vms"], res["grand"]["cpu"]), (9, 38))
        roles = [(n["role"], n["cpu"], n["ram"], n["diskTotal"]) for n in prod["nodes"]]
        self.assertEqual(roles, [("Сервер приложений Directum RX", 8, 20, 100), ("СУБД", 4, 8, 230),
                                 ("Объектное хранилище S3", 2, 8, 250), ("Полнотекстовый поиск", 4, 8, 100),
                                 ("Мониторинг и журналы", 4, 8, 100)])

    def test_presets_match_page_buttons(self):
        """Профили --preset повторяют кнопки на странице калькулятора."""
        pages = dict((name, h) for name, h, _ in SERVERS)
        pairs = [("small", "preset_small_100"), ("mid", "preset_mid_500"), ("big", "preset_big_2000_k8s_ns"),
                 ("holding", "preset_holding_10000_k8s_full")]
        for preset, name in pairs:
            with self.subTest(preset):
                a = S.compute(S.servers_inputs(preset=preset))
                b = S.compute(S.servers_inputs(url="#" + pages[name]))
                self.assertEqual(digest(a), digest(b))

    def test_js_helpers(self):
        self.assertEqual([S.js_round(x) for x in (0.5, 1.5, 2.5, -0.5, -1.5, 0.49999999999999994)], [1, 2, 3, 0, -1, 0])
        self.assertEqual(S.up(20.000000001, 10), 20)
        self.assertEqual(S.up(20.1, 10), 30)
        self.assertEqual(S.even(7), 8)
        self.assertEqual(S.fmt_gb(999), "999 ГБ")
        self.assertEqual(S.fmt_gb(1260), "1,3 ТБ")
        self.assertEqual(S.fmt_gb(1000), "1 ТБ")
        self.assertEqual(S.js_str(1.2), "1.2")
        self.assertEqual(S.js_str(20.0), "20")

    def test_decode_like_page(self):
        """decode() со страницы: неизвестные ключи и пары без значения пропускаются, мусор в числе это 0."""
        d = S.decode_servers_url("https://drxinfra.ru/sizing.html#users=500&foo=1&ha&docKB=abc&mobile=12x&ver=9.9")
        self.assertEqual(d, {"users": 500.0, "docKB": 0.0, "mobile": 12.0, "ver": "26.2"})
        with self.assertRaises(S.InputError):
            S.servers_inputs(url="#store=nfs")


