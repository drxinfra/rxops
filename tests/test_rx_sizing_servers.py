def strings_sha(res):
    parts = []
    for c in res["contours"]:
        parts.append([c["title"], c["kind"]])
        for n in c["nodes"]:
            parts.append([n["role"], n["sw"], n["note"]] + [x["name"] for x in n["disk"]])
        if c["k8sQuota"]:
            parts.append([c["k8sQuota"]["pods"]])
    for w in res["warnings"]:
        parts.append([w["lvl"], w["text"]])
    return hashlib.sha256(json.dumps(parts, ensure_ascii=False).encode("utf-8")).hexdigest()[:16]


def node_row(n):
    row = [n["role"], n["n"], n["cpu"], n["ram"], [x["gb"] for x in n["disk"]]]
    if n.get("k8s"):
        row.append("k8s")
    if n.get("storageOnly"):
        row.append("том")
    return row


def digest(res):
    d, g = res["d"], res["grand"]
    contours = []
    for c in res["contours"]:
        t, q, lg = c["totals"], c["k8sQuota"], c["logs"]
        contours.append([c["kind"], [t["vms"], t["cpu"], t["ram"], t["disk"]], c["backupGB"],
                         [lg["perDay"], lg["gb"], lg["metricsGb"]],
                         None if not q else [q["reqCpu"], q["reqRam"], q["limCpu"], q["limRam"], q["pv"]],
                         [node_row(n) for n in c["nodes"]]])
    return {
        "d": [d["U"], d["T"], d["M"], d["storeGB"], d["dbGB"], d["docsTotal"]],
        "grand": [g["vms"], g["cpu"], g["ram"], g["disk"], g["backup"]],
        "warn": "".join(w["lvl"][0] for w in res["warnings"]),
        "strings": strings_sha(res),
        "contours": contours,
    }


